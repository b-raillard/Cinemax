"""Turns the network logos into monochrome TEMPLATE images + the Swift catalogue.

Input : networks.json, mask_overrides.json, _originals/ (fetch_networks.py).
Output: Resources/Assets.xcassets/Networks/network-<id>.imageset (white glyph on
        transparent, 128 px tall, template rendering) and
        Shared/DesignSystem/NetworkLogoCatalogue.swift (name -> asset).
        apercu.png: every mask on a dark and a light pill — CHECK IT.

How a logo becomes a mask (mask_overrides.json picks one by TMDb network id):
  alpha    (default) the logo's own transparency
  knockout (default when the whole border is opaque) distance from the box colour
  nowhite  white detail inside a coloured shape becomes a hole (ABC, RTL+, TF1…)
Requires Pillow.
"""
import json, os, shutil
from PIL import Image, ImageChops, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
CATALOG = os.path.join(ROOT, 'Resources', 'Assets.xcassets', 'Networks')
SWIFT = os.path.join(ROOT, 'Shared', 'DesignSystem', 'NetworkLogoCatalogue.swift')
H, MAXW = 128, 1024

nets = json.load(open(os.path.join(HERE, 'networks.json')))
over = json.load(open(os.path.join(HERE, 'mask_overrides.json')))


def mode_for(im):
    a = im.getchannel('A')
    w, h = a.size
    border = [a.getpixel((x, y)) for x in range(0, w, 4) for y in (0, h - 1)] + \
             [a.getpixel((x, y)) for y in range(0, h, 4) for x in (0, w - 1)]
    return 'knockout' if sum(v > 200 for v in border) / len(border) > 0.95 else 'alpha'


def make_mask(im, mode):
    rgb, a = im.convert('RGB'), im.getchannel('A')
    if mode == 'knockout':
        w, h = rgb.size
        cs = [rgb.getpixel(p) for p in ((1, 1), (w - 2, 1), (1, h - 2), (w - 2, h - 2))]
        bg = max(set(cs), key=cs.count)
        diff = ImageChops.difference(rgb, Image.new('RGB', rgb.size, bg)).convert('L')
        return ImageChops.multiply(diff.point(lambda v: min(255, v * 3)), a)
    if mode == 'nowhite':
        keep = rgb.convert('L').point(lambda v: 255 if v < 200 else max(0, (235 - v) * 7))
        return ImageChops.multiply(keep, a)
    return a


if os.path.isdir(CATALOG):
    shutil.rmtree(CATALOG)
os.makedirs(CATALOG)
json.dump({'info': {'author': 'xcode', 'version': 1}, 'properties': {'provides-namespace': True}},
          open(os.path.join(CATALOG, 'Contents.json'), 'w'), indent=2)

entries, seen, made = [], set(), []
for n in nets:  # sorted by series count: on a name clash the most used network wins
    key = n['name'].strip().casefold()
    if not n.get('file') or key in seen:
        continue
    seen.add(key)
    im = Image.open(os.path.join(HERE, '_originals', n['file'])).convert('RGBA')
    m = make_mask(im, over.get(str(n['id'])) or mode_for(im))
    box = m.point(lambda v: 255 if v > 12 else 0).getbbox()
    m = m.crop(box) if box else m
    w, h = m.size
    s = min(H / h, MAXW / w)
    m = m.resize((max(1, round(w * s)), max(1, round(h * s))), Image.LANCZOS)
    asset = f"network-{n['id']}"
    folder = os.path.join(CATALOG, asset + '.imageset')
    os.makedirs(folder)
    Image.merge('LA', (Image.new('L', m.size, 255), m)).save(os.path.join(folder, asset + '.png'), optimize=True)
    json.dump({'images': [{'filename': asset + '.png', 'idiom': 'universal'}],
               'info': {'author': 'xcode', 'version': 1},
               'properties': {'template-rendering-intent': 'template'}},
              open(os.path.join(folder, 'Contents.json'), 'w'), indent=2)
    made.append((n, os.path.join(folder, asset + '.png')))
    entries.append((key, 'Networks/' + asset, n['name']))

lines = ['// GENERATED by design/network-logos/build_assets.py — do not edit by hand.',
         '// TMDb network name (trimmed, case-folded) -> template image in Assets.xcassets/Networks.',
         '',
         'enum NetworkLogoCatalogue {',
         '    static let assets: [String: String] = [']
rows = sorted(entries)
lines += [f'        {json.dumps(k, ensure_ascii=False)}: "{a}"{"," if i < len(rows) - 1 else ""}  // {name}'
          for i, (k, a, name) in enumerate(rows)]
lines += ['    ]',
          '',
          '    /// The first of `studios` that has a logo, with its name as Jellyfin spells it.',
          '    /// A series lists its networks AND its production companies; only the',
          '    /// networks have a logo, whatever their order.',
          '    static func logo(forStudios studios: [String]) -> (name: String, asset: String)? {',
          '        for name in studios {',
          '            let key = name.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()',
          '            if let asset = assets[key] { return (name, asset) }',
          '        }',
          '        return nil',
          '    }',
          '}', '']
open(SWIFT, 'w').write('\n'.join(lines))

# review sheet
cols, cw, ch = 4, 300, 150
sheet = Image.new('RGB', (cols * cw, ((len(made) + cols - 1) // cols) * ch), (40, 40, 48))
d = ImageDraw.Draw(sheet)
for i, (n, png) in enumerate(made):
    x, y = (i % cols) * cw, (i // cols) * ch
    g = Image.open(png)
    g.thumbnail((cw - 30, 40))
    for j, (bgc, fg) in enumerate((((12, 12, 16), (255, 255, 255)), ((246, 246, 248), (20, 20, 24)))):
        cell = Image.new('RGB', (cw - 20, 52), bgc)
        cell.paste(Image.new('RGB', g.size, fg), ((cw - 20 - g.size[0]) // 2, (52 - g.size[1]) // 2), g.getchannel('A'))
        sheet.paste(cell, (x + 10, y + 26 + j * 58))
    d.text((x + 10, y + 6), n['name'][:30], fill=(220, 220, 230))
sheet.save(os.path.join(HERE, 'apercu.png'))
print('assets', len(made), 'catalogue entries', len(entries))
